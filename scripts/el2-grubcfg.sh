#!/bin/sh
# Write /boot/grub/el2.cfg: one GRUB entry that boots the newest kernel with
# the X13s EL2 device tree (read by grubel2.efi, see el2-install.sh).
# Installed as /etc/kernel/postinst.d/zz-el2-grubcfg so kernel updates keep it
# current; kernel postinst hooks get the version as $1 (ignored, newest wins).
set -eu

OUT=${EL2_GRUBCFG:-/boot/grub/el2.cfg}
DTB=device-tree/qcom/sc8280xp-lenovo-thinkpad-x13s-el2.dtb

# Same kernel arguments grub-mkconfig would use.
GRUB_CMDLINE_LINUX="" GRUB_CMDLINE_LINUX_DEFAULT=""
. /etc/default/grub
for f in /etc/default/grub.d/*.cfg; do [ -e "$f" ] && . "$f"; done
# Keep boot messages visible: "quiet splash" hides why an EL2 boot stops.
args=$(echo "$GRUB_CMDLINE_LINUX $GRUB_CMDLINE_LINUX_DEFAULT" | sed 's/\bquiet\b//; s/\bsplash\b//')

ver=$(linux-version list | linux-version sort --reverse | while read -r v; do
        [ -e "/boot/vmlinuz-$v" ] && [ -e "/lib/firmware/$v/$DTB" ] && { echo "$v"; break; }
      done)
[ -n "$ver" ] || { echo "el2-grubcfg: no kernel with $DTB" >&2; exit 0; }

uuid=$(findmnt -no UUID /)

# Ubuntu's arm64 vmlinuz is a stubble (systemd-stub) image: it carries
# .dtbauto device trees and installs the one matching .hwids, replacing the
# dtb GRUB passed. Boot the bare kernel from its .linux section instead, so the
# EL2 dtb survives. Normal boots keep using the stubbed image.
KDIR=${EL2_KDIR:-/boot/el2}
mkdir -p "$KDIR"
kernel="$KDIR/vmlinuz-$ver"
if [ ! -s "$kernel" ] || [ "/boot/vmlinuz-$ver" -nt "$kernel" ]; then
	objcopy -O binary --only-section=.linux "/boot/vmlinuz-$ver" "$kernel.new"
	[ "$(head -c2 "$kernel.new")" = MZ ] || { echo "el2-grubcfg: no .linux PE in /boot/vmlinuz-$ver" >&2; rm -f "$kernel.new"; exit 1; }
	mv "$kernel.new" "$kernel"
fi
# Drop extracted kernels whose package is gone.
for k in "$KDIR"/vmlinuz-*; do
	[ -e "/boot/${k##*/}" ] || rm -f "$k"
done

cat > "$OUT.new" <<EOF
# Generated by el2-grubcfg ($(date -I)); do not edit.
search --no-floppy --fs-uuid --set=root $uuid
set default=0
set timeout=3
menuentry 'Ubuntu $ver (EL2 / KVM)' {
	linux	/boot/el2/vmlinuz-$ver root=UUID=$uuid ro $args
	initrd	/boot/initrd.img-$ver
	devicetree	/lib/firmware/$ver/$DTB
}
menuentry 'EL2 diagnostics (does not boot)' {
	echo '== EFI config tables before GRUB (look for DEVICE TREE / b1b621d5):'
	lsefisystab
	echo '== firmware FDT model (error = no firmware DTB):'
	fdtdump -p model
	set debug=fdt
	echo '== loading the EL2 dtb:'
	devicetree	/lib/firmware/$ver/$DTB
	set debug=
	echo '== take a photo, then press any key for the menu'
	sleep --interruptible 600
}
menuentry 'UEFI firmware settings' {
	fwsetup
}
EOF
mv "$OUT.new" "$OUT"
echo "el2-grubcfg: $OUT -> $ver"
