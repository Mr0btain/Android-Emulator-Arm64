#!/usr/bin/env python3
"""Generate sources.list from a platform/manifest branch (default.xml).

Keeps the projects `repo init -b <branch>` would sync by default, minus:
  - groups containing "notdefault" (x86/darwin/windows host prebuilts,
    bison/flex/m4: we use the system ones)
  - test/dev-only projects (EXCLUDE)
and checks out the big multi-platform prebuilt repos sparsely (SPARSE).
Revisions are branch names; run fetch-sources.sh + build, then
scripts/pin-sources.sh to pin SHAs.

usage: gen-sources.py <branch> > sources.list
"""
import base64
import sys
import urllib.request
import xml.etree.ElementTree as ET

EXCLUDE = {
    "external/mobly-bundled-snippets",
    "prebuilts/android-emulator-build/system-images",
    "prebuilts/studio/jdk",
    "tools/repohooks",
    "external/moltenvk",  # macOS only
}
SPARSE = {
    "prebuilts/android-emulator-build/qt": "linux-aarch64",
    "prebuilts/android-emulator-build/qemu-android-deps": "linux-aarch64",
}

branch = sys.argv[1]
url = f"https://android.googlesource.com/platform/manifest/+/refs/heads/{branch}/default.xml?format=TEXT"
root = ET.fromstring(base64.b64decode(urllib.request.urlopen(url).read()))
default_rev = root.find("default").get("revision")

print("# <path> <aosp-project> <revision> [sparse-dirs,comma,separated]")
print(f"# Generated by scripts/gen-sources.py from platform/manifest {branch}.")
for p in root.iter("project"):
    path = p.get("path") or p.get("name")
    if "notdefault" in p.get("groups", "") or path in EXCLUDE:
        continue
    rev = p.get("revision") or default_rev
    print(" ".join(x for x in (path, p.get("name"), rev, SPARSE.get(path)) if x))
